/**
 * The admission record for an exact mutate selector. Fails closed when a
 * selector has no verified record, so a required entry can never silently
 * lose its provenance.
 */
export function admissionRecord(selector: string): AdmissionRecord {
  const record = RECORDS[selector];
  if (record === undefined) {
    throw new Error(`no verified admission record for selector '${selector}'`);
  }
  return record;
}

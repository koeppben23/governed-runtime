/**
 * SDK Type Baseline Snapshot Tool.
 *
 * Compares the pinned native @opencode/plugin + @opencode/client contracts against
 * committed baseline files. Fails with exit 1 if any drift is detected.
 *
 * Usage:
 *   node scripts/sdk-type-snapshot.mjs                      # Check opencode (default)
 *   node scripts/sdk-type-snapshot.mjs --update             # Update opencode baseline
 *   node scripts/sdk-type-snapshot.mjs --platform opencode  # Explicit platform
 *   node scripts/sdk-type-snapshot.mjs --platform claude-code --update
 *   node scripts/sdk-type-snapshot.mjs --platform codex --update
 *   node scripts/sdk-type-snapshot.mjs --platform mcp --update
 *   node scripts/sdk-type-snapshot.mjs --platform governance --update
 *
 * Baseline directory structure:
 *   .sdk-baselines/opencode/       — OpenCode plugin type definitions
 *   .sdk-baselines/claude-code/    — Claude Code hook protocol schemas
 *   .sdk-baselines/codex/          — Codex hook protocol schemas
 *   .sdk-baselines/mcp/            — MCP tool input schemas (per-tool)
 *   .sdk-baselines/governance/     — HAI governance surface schemas
 *
 * Source files (opencode):
 *   node_modules/@opencode/plugin/dist/promise/*.d.ts
 *   node_modules/@opencode/client/dist/promise/generated/types.d.ts
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');

export class SdkContractError extends Error {
  code = 'SDK_CONTRACT_INVALID';
}

// ── Platform Definitions ─────────────────────────────────────────────────────

const nativePluginFile = (name) => ({
  source: path.join(root, 'node_modules', '@opencode', 'plugin', 'dist', 'promise', `${name}.d.ts`),
  baseline: path.join(root, '.sdk-baselines', 'opencode', `plugin-${name}.d.ts`),
  label: `@opencode/plugin/dist/promise/${name}.d.ts`,
});
const clientTypes = path.join(
  root,
  'node_modules',
  '@opencode',
  'client',
  'dist',
  'promise',
  'generated',
  'types.d.ts',
);

export const PLATFORMS = {
  opencode: {
    files: [
      ...['index', 'plugin', 'tool', 'session', 'event', 'registration'].map(nativePluginFile),
      {
        source: clientTypes,
        baseline: path.join(root, '.sdk-baselines', 'opencode', 'client-event-contract.d.ts'),
        label: '@opencode/client#EventSubscribeOutput/V2Event',
        derive: deriveEventContract,
      },
      {
        source: clientTypes,
        baseline: path.join(root, '.sdk-baselines', 'opencode', 'client-message-contract.d.ts'),
        label: '@opencode/client#SessionMessageInfo/ToolContent',
        derive: deriveMessageContract,
      },
      {
        source: path.join(root, 'node_modules', '@opencode', 'schema', 'dist', 'tool.d.ts'),
        baseline: path.join(root, '.sdk-baselines', 'opencode', 'schema-tool.d.ts'),
        label: '@opencode/schema/dist/tool.d.ts',
      },
    ],
    versionSources: ['plugin', 'client'].map((name) =>
      path.join(root, 'node_modules', '@opencode', name, 'package.json'),
    ),
    versionFile: path.join(root, '.sdk-baselines', 'opencode', 'version.json'),
  },
  'claude-code': {
    files: [], // JSON schema files — no source comparison, generated by tests
    versionFile: path.join(root, '.sdk-baselines', 'claude-code', 'version.json'),
  },
  codex: {
    files: [], // JSON schema files — no source comparison, generated by tests
    versionFile: path.join(root, '.sdk-baselines', 'codex', 'version.json'),
  },
  mcp: {
    files: [], // JSON schema files — generated from Zod tool schemas
    versionFile: path.join(root, '.sdk-baselines', 'mcp', 'version.json'),
  },
  governance: {
    files: [], // JSON schema files — generated from HAI interface
    versionFile: path.join(root, '.sdk-baselines', 'governance', 'version.json'),
  },
};

// ── Helpers ──────────────────────────────────────────────────────────────────

/**
 * Normalize content for comparison: convert CRLF to LF, trim trailing
 * whitespace per line, ensure single trailing newline.
 */
function normalize(content) {
  return (
    content
      .replace(/\r\n/g, '\n')
      .split('\n')
      .map((line) => line.trimEnd())
      .join('\n')
      .replace(/\n+$/, '') + '\n'
  );
}
export { normalize };

function sha256(content) {
  return createHash('sha256').update(content).digest('hex');
}
export { sha256 };

/**
 * Extract the native event union plus its member declarations from the generated
 * OpenCode SDK types. The result is a compact, reviewable contract snapshot:
 * referenced helper types stay in the SDK file and are not duplicated.
 */
function deriveEventContract(content) {
  const unionMatch = content.match(/^export type V2Event = ([^\n]+);$/m);
  if (!unionMatch) {
    throw new SdkContractError('deriveEventContract: V2Event union not found in client types');
  }
  const members = unionMatch[1]
    .split('|')
    .map((member) => member.trim())
    .filter(Boolean);

  const declarations = members.map((member) => {
    return declaration(content, member);
  });

  return [
    '// Native OpenCode V2 event contract; SDK declarations are not installed-host proof.',
    '// Source: @opencode/client/dist/promise/generated/types.d.ts',
    '// Generated by scripts/sdk-type-snapshot.mjs --update. Do not edit manually.',
    '// Referenced helper types remain in the client; structured errors are pinned here.',
    '',
    unionMatch[0],
    declaration(content, 'EventSubscribeOutput'),
    declaration(content, 'SessionStructuredError'),
    '',
    declarations.join('\n\n'),
  ].join('\n');
}
export { deriveEventContract };

function declaration(content, name) {
  const match = content.match(
    new RegExp(`^export type ${name} = (?:\\{[\\s\\S]*?^\\};|[^\\n]+;)`, 'm'),
  );
  if (!match) throw new SdkContractError(`Native declaration for ${name} not found`);
  return match[0];
}

/** Pin native raw history and tool states without synthesizing old message/part identities. */
export function deriveMessageContract(content) {
  const names = [
    'SessionMessageInfo',
    'SessionMessageAssistant',
    'SessionMessageAssistantTool',
    'SessionMessageToolStateStreaming',
    'SessionMessageToolStateRunning',
    'SessionMessageToolStateCompleted',
    'SessionMessageToolStateError',
    'ToolContent',
    'ToolTextContent',
    'ToolFileContent',
    'SessionStructuredError',
  ];
  const declarations = names.map((name) => declaration(content, name));
  return [
    '// Generated by scripts/sdk-type-snapshot.mjs --update. Do not edit manually.',
    '// Native V2 history contract, not release/capture or regular termination proof.',
    '',
    ...declarations,
  ].join('\n\n');
}

/** Read a configured source, applying its derivation when present. */
function readConfiguredSource(file) {
  const raw = fs.readFileSync(file.source, 'utf-8');
  return file.derive ? file.derive(raw) : raw;
}
export { readConfiguredSource };

/**
 * Produce a minimal unified-diff-style output showing which lines changed.
 */
function simpleDiff(label, baselineContent, sourceContent) {
  const baseLines = baselineContent.split('\n');
  const srcLines = sourceContent.split('\n');
  const lines = [];
  const maxLen = Math.max(baseLines.length, srcLines.length);
  for (let i = 0; i < maxLen; i++) {
    const bl = baseLines[i] ?? '';
    const sl = srcLines[i] ?? '';
    if (bl !== sl) {
      lines.push(`  Line ${i + 1}:`);
      lines.push(`    - ${bl}`);
      lines.push(`    + ${sl}`);
    }
  }
  return [`--- ${label} (baseline)`, `+++ ${label} (installed)`, ...lines].join('\n');
}

// ── Argument Parsing ─────────────────────────────────────────────────────────

function parsePlatformArg() {
  const idx = process.argv.indexOf('--platform');
  if (idx === -1) return 'opencode';
  const value = process.argv[idx + 1];
  if (!value || !Object.keys(PLATFORMS).includes(value)) {
    console.error(`ERROR: Invalid --platform value: ${value}`);
    console.error(`Valid platforms: ${Object.keys(PLATFORMS).join(', ')}`);
    process.exit(1);
  }
  return value;
}

// ── Main ─────────────────────────────────────────────────────────────────────

function run() {
  const isUpdate = process.argv.includes('--update');
  const platform = parsePlatformArg();
  const config = PLATFORMS[platform];

  if (!config) {
    console.error(`ERROR: Unknown platform: ${platform}`);
    process.exit(1);
  }

  const FILES = config.files;

  // For platforms without source-comparison files (schema-only), skip file checks
  if (FILES.length === 0) {
    if (isUpdate) {
      console.log(`Platform "${platform}" uses schema-generated baselines.`);
      console.log(`Run the contract tests with --update to regenerate.`);
    } else {
      // Check that baseline directory exists
      const baseDir = path.join(root, '.sdk-baselines', platform);
      if (!fs.existsSync(baseDir)) {
        console.error(`ERROR: Baseline directory missing: .sdk-baselines/${platform}/`);
        console.error(`Run the SDK contract tests to generate baselines.`);
        process.exit(1);
      }
      console.log(`OK: .sdk-baselines/${platform}/ exists (schema baselines managed by tests).`);
    }
    process.exit(0);
  }

  // ── Pre-flight: source files must exist ────────────────────────────────────
  for (const f of FILES) {
    if (!fs.existsSync(f.source)) {
      console.error(`ERROR: Source file not found: ${f.source}`);
      console.error('Run "npm ci" to install dependencies first.');
      process.exit(1);
    }
  }

  if (isUpdate) {
    // ── Update mode ──────────────────────────────────────────────────────────
    for (const f of FILES) {
      const content = normalize(readConfiguredSource(f));
      fs.mkdirSync(path.dirname(f.baseline), { recursive: true });
      fs.writeFileSync(f.baseline, content, 'utf-8');
      console.log(`Updated: ${path.relative(root, f.baseline)} (${sha256(content).slice(0, 12)})`);
    }

    // Write version metadata
    const packages = readNativeVersions(config);
    const meta = {
      platform,
      updated: new Date().toISOString(),
      packages,
      files: FILES.map((f) => ({
        label: f.label,
        hash: sha256(normalize(readConfiguredSource(f))),
      })),
    };
    fs.mkdirSync(path.dirname(config.versionFile), { recursive: true });
    fs.writeFileSync(config.versionFile, JSON.stringify(meta, null, 2) + '\n', 'utf-8');
    console.log(`Baseline updated for platform "${platform}" (${JSON.stringify(packages)})`);
    process.exit(0);
  }

  // ── Check mode ─────────────────────────────────────────────────────────────
  let drifted = false;
  const packages = readNativeVersions(config);
  const metadata = JSON.parse(fs.readFileSync(config.versionFile, 'utf-8'));
  if (JSON.stringify(metadata.packages) !== JSON.stringify(packages)) {
    console.error('DRIFT DETECTED: native package version metadata');
    drifted = true;
  }
  const expectedFiles = FILES.map((file) => ({
    label: file.label,
    hash: sha256(normalize(readConfiguredSource(file))),
  }));
  if (JSON.stringify(metadata.files) !== JSON.stringify(expectedFiles)) {
    console.error('DRIFT DETECTED: declaration inventory or metadata hashes');
    drifted = true;
  }
  const pins = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).dependencies;
  if (Object.entries(packages).some(([name, version]) => pins[name] !== version)) {
    console.error('DRIFT DETECTED: native dependency pins do not match the installed packages');
    drifted = true;
  }
  for (const f of FILES) {
    if (!fs.existsSync(f.baseline)) {
      console.error(`ERROR: Baseline file missing: ${path.relative(root, f.baseline)}`);
      console.error(
        `Run "node scripts/sdk-type-snapshot.mjs --platform ${platform} --update" to create the baseline.`,
      );
      drifted = true;
      continue;
    }

    const sourceContent = normalize(readConfiguredSource(f));
    const baselineContent = normalize(fs.readFileSync(f.baseline, 'utf-8'));

    if (sourceContent !== baselineContent) {
      console.error(`DRIFT DETECTED: ${f.label}`);
      console.error(`  Baseline hash: ${sha256(baselineContent).slice(0, 12)}`);
      console.error(`  Installed hash: ${sha256(sourceContent).slice(0, 12)}`);
      console.error('');
      console.error(simpleDiff(f.label, baselineContent, sourceContent));
      console.error('');
      drifted = true;
    } else {
      console.log(`OK: ${f.label} (${sha256(sourceContent).slice(0, 12)})`);
    }
  }

  if (drifted) {
    console.error('');
    console.error('SDK type drift detected. Review the changes above, then run:');
    console.error(`  node scripts/sdk-type-snapshot.mjs --platform ${platform} --update`);
    process.exit(1);
  }

  console.log(`All SDK type baselines match for platform "${platform}".`);
  process.exit(0);
}

/** Missing/malformed metadata is a failure, never an "unknown" baseline. */
export function readNativeVersions(config) {
  return Object.fromEntries(
    config.versionSources.map((source) => {
      const pkg = JSON.parse(fs.readFileSync(source, 'utf-8'));
      if (
        !/^@opencode\/(plugin|client)$/.test(pkg.name) ||
        !/^2\.\d+\.\d+(?:-[\w.-]+)?$/.test(pkg.version)
      )
        throw new SdkContractError(`Invalid native package metadata: ${source}`);
      return [pkg.name, pkg.version];
    }),
  );
}

// Only run the CLI when executed directly; importing the module for tests must
// not trigger filesystem checks or process.exit.
const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : null;
if (invokedPath === fileURLToPath(import.meta.url)) {
  run();
}
